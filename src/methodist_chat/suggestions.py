def suggestions_cache_key(
    filename: str,
    head_text: str,
    context: str = "",
) -> str:
    """Детерминированный ключ кэша на основе filename + head + context.

    ``context`` — последний ответ ассистента (или иной маркер диалога).
    Когда меняется ответ модели, меняется и ключ → подсказки автоматически
    регенерируются на следующем rerender Streamlit'а.
    """
    payload = f"{filename}|{head_text[:2000]}|{context[:2000]}"
    h = hashlib.sha256(payload.encode()).hexdigest()[:16]
    return f"suggestions_{h}"
