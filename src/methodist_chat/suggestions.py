# Символы/последовательности, с которых может начинаться «мусорный» префикс
# (нумерация, маркеры списка, двоеточия, тире и т.п.). Режем рекурсивно,
# пока остаются совпадения — это ловит случаи вроде «1.- », «• 1) »,
# «Подсказка 3: » и т.д.
_LEADING_NOISE_RE = re.compile(
    r"^\s*(?:"
    r"\d+[.)\]:\-—–]+|"        # 1.  2)  3]  4:  5-  6—  7–
    r"[\-—–*+•▪●■▸▶→>→»]+|"      # маркеры списка
    r"[#]+|"                    # заголовочные #
    r"(?:Подсказка|Действие|Шаг|"  # «Подсказка 1:»
    r"Suggestion|Action|Step|Hint)\s*\d*\s*[:.)\-]\s*"
    r")",
    re.IGNORECASE,
)

# Строки-мусор — вступления, постамбулы, «мысленные процессы» модели.
# Проверяем каждую строку после очистки префикса: если она или начинается с
# такого паттерна, или весьма похожа на явный «я-формат» — выкидываем.
_NOISE_PHRASE_RE = re.compile(
    r"^(?:"
    r"конечно|хорошо|ладно|понятно|безусловно|разумеется|да|"
    r"вот|вот\s+\d|ниже|выше|приведу|приведён|привожу|"
    r"предлагаю|предлагаю\s+\d|варианты|возможные|"
    r"я\s|я,|мы\s|мы,|давай\s|давайте|хм+|угу|окей|"
    r"думаю|думаю,|размышляю|рассуждая|сейчас\s+подума|"
    r"sure|okay|of\s+course|here\s+are|here'?s|let\s+me|i'?ll|i\s+will|"
    r"thought|thinking|reasoning|analysis|let'?s"
    r")(?:\b|[\s,:.!?])",
    re.IGNORECASE,
)

# Блоки «мышления» в разных нотациях: <think>...</think>, <reasoning>,
# [thinking]... [/thinking], и т.п. Режем их из raw-ответа ДО разбора по строкам.
_THINK_BLOCK_RE = re.compile(
    r"<\s*(think|thinking|reasoning|reason|scratchpad)\s*>.*?"
    r"<\s*/\s*\1\s*>",
    re.IGNORECASE | re.DOTALL,
)
_THINK_BRACKET_RE = re.compile(
    r"\[\s*(think|thinking|reasoning|reason|scratchpad)\s*\].*?"
    r"\[\s*/\s*\1\s*\]",
    re.IGNORECASE | re.DOTALL,
)

# Командные глаголы, с которых должна начинаться подсказка-команда. Системный
# промпт явно требует командный тон («Проверь…», «Найди…» и т.д.). Если строка
# не начинается с одного из этих глаголов — это почти точно пояснение
# или «мысль» модели, а не действие, которое можно отправить в чат.
_COMMAND_VERBS = (
    "проверь", "найди", "предложи", "сравни", "оцени",
    "уточни", "раскрой", "покажи", "сформируй", "сделай",
    "дополни", "подбери", "поищи", "переформулируй",
    "объясни", "выдели", "составь", "построй", "рассчитай",
    "выбери", "обнови", "актуализируй", "перепроверь",
    "переведи", "оформи", "опиши", "распиши", "сформулируй",
    "сверь", "сопоставь", "выяви", "отметь", "подготовь",
    "перескажи", "суммируй", "сократи", "расширь", "добавь",
    "убери", "удали", "исправь", "замени", "перепиши",
)
_COMMAND_VERB_RE = re.compile(
    r"^(?:" + "|".join(_COMMAND_VERBS) + r")[а-я]{0,3}\b",
    re.IGNORECASE,
)

# Разумные границы длины подсказки (в символах).
_MIN_LEN = 10   # «Найди ФГОС» — 9 симв., уже на границе
_MAX_LEN = 200  # всё длиннее — явно пояснение, а не команда


def _strip_leading_noise(s: str) -> str:
    """Рекурсивно срезает все «мусорные» ведущие префиксы.

    Примеры вход/выход:
        "1. Найди ФГОС"     -> "Найди ФГОС"
        "• Найди ФГОС"     -> "Найди ФГОС"
        "1.- Найди ФГОС"   -> "Найди ФГОС"
        "Подсказка 3: Найди ФГОС" -> "Найди ФГОС"
    """
    prev = None
    cur = s
    # До фиксированной точки — вряд ли больше 5 итераций в реальности.
    for _ in range(5):
        if cur == prev:
            break
        prev = cur
        cur = _LEADING_NOISE_RE.sub("", cur).strip()
    return cur


def _looks_like_noise(line: str) -> bool:
    """True, если строка явно не подсказка."""
    if not line:
        return True
    if _NOISE_PHRASE_RE.match(line):
        return True
    # Строка без букв (одни символы/цифры) — мусор
    if not re.search(r"[А-ЯёЁа-яa-zA-Z]", line):
        return True
    return False


def _parse_suggestions(raw: str) -> list[str]:
    """Парсит LLM-ответ в список подсказок с жёсткой валидацией.

    Отбрасывает:
      * блоки «мышления» (<think>…</think>, [reasoning]…[/reasoning] и т.п.);
      * вступления/постамбулы («Конечно!», «Вот 5 действий:», «Ниже…»);
      * любые ведущие нумерации/маркеры (1., 2), -, *, •, ▪, →, >);
      * слишком короткие (<10) и слишком длинные (>200) строки;
      * строки без командного глагола в начале («Проверь…», «Найди…» и т.д.);
      * дубликаты по нормализованной форме (lower + без пробелов-хвоста).

    Возвращает до 6 подсказок; меньше ок (вызывающий код НЕ дополняет статикой).
    """
    if not raw:
        return []
    # Шаг 1: вырезаем «мыслительные» блоки ЦЕЛИКОМ, до разбора по строкам.
    cleaned_raw = _THINK_BLOCK_RE.sub("", raw)
    cleaned_raw = _THINK_BRACKET_RE.sub("", cleaned_raw)

    out: list[str] = []
    seen_norm: set[str] = set()
    for line in cleaned_raw.splitlines():
        line = line.strip()
        if not line:
            continue
        # Шаг 2: режем нумерацию/маркеры/вступительные ярлыки.
        cleaned = _strip_leading_noise(line)
        if not cleaned:
            continue
        # Шаг 3: явный мусор (вступления, мысли, символьный шум).
        if _looks_like_noise(cleaned):
            continue
        # Шаг 4: длина.
        if len(cleaned) < _MIN_LEN or len(cleaned) > _MAX_LEN:
            continue
        # Шаг 5: требуем командный глагол в начале.
        if not _COMMAND_VERB_RE.match(cleaned):
            continue
        # Шаг 6: дедупликация по нормализованной форме.
        norm = re.sub(r"\s+", " ", cleaned).strip(" .!?:;,").lower()
        if norm in seen_norm:
            continue
        seen_norm.add(norm)
        out.append(cleaned)
        if len(out) >= 6:
            break
    return out


def generate_suggestions(
    *,
    llm: QuickLLM | None,
    filename: str,
    head_text: str,
    kind: str | None = None,
    last_user_message: str = "",
    last_assistant_message: str = "",
) -> list[str]:
    """Генерирует подсказки для файла. LLM-вызов + fallback на статику.

    Если задан ``last_assistant_message`` — переключаемся в follow-up режим:
    подсказки строятся как **продолжение** диалога, а не «с нуля» по файлу.
    """
    if kind is None:
        kind = detect_doc_kind(filename, head_text)
    if kind not in BASE_SUGGESTIONS:
        kind = "неизвестно"

    is_followup = bool(last_assistant_message.strip())

    if llm is not None:
        try:
            if is_followup:
                user_prompt = (
                    f"Файл: «{filename}» (тип: {kind})\n\n"
                    f"Последний вопрос пользователя:\n"
                    f"{last_user_message[:500]}\n\n"
                    f"Последний ответ ассистента:\n"
                    f"{last_assistant_message[:1500]}\n\n"
                    "Предложи 5 follow-up действий."
                )
                system = _SUGGEST_FOLLOWUP_SYSTEM
            else:
                user_prompt = (
                    f"Файл: «{filename}»\n"
                    f"Тип: {kind}\n"
                    f"Начало документа:\n{head_text[:1500]}"
                )
                system = _SUGGEST_SYSTEM
            raw = llm.quick(
                system=system,
                user=user_prompt,
                temperature=0.4,
                max_tokens=400,
            )
            parsed = _parse_suggestions(raw)
            # НЕ добиваем статикой: если модель вернула меньше 5 подсказок,
            # это осознанный выбор («больше релевантных действий нет»).
            # Статический fallback срабатывает ТОЛЬКО при полном отсутствии
            # валидных подсказок (LLM вернул чистый мусор) или при исключении.
            if parsed:
                log.info(
                    "LLM-подсказки %s (%d): %s",
                    "follow-up" if is_followup else "init",
                    len(parsed),
                    parsed[0][:60],
                )
                return parsed
            log.warning(
                "LLM не вернул валидных подсказок (всё отфильтровано), "
                "fallback на статику"
            )
        except Exception as exc:
            log.warning("Ошибка генерации подсказок: %s, fallback на статику", exc)

    if is_followup:
        return list(BASE_FOLLOWUP_SUGGESTIONS[:5])
    return list(BASE_SUGGESTIONS[kind])


