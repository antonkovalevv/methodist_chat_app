def detect_doc_kind(filename: str, head: str) -> str:
    """Определяет тип документа по имени файла и первым ~1500 символам.

    Возвращает одно из значений ``DOC_KINDS``.
    """
    # Нормализуем имя: разделители (_, ., -) → пробел, чтобы «РПД_информатика»
    # читалось как два токена и матчилось паттерном на «РПД» как отдельное слово.
    fname_norm = re.sub(r"[_.\-/\\]+", " ", filename or "")
    combined = f"{fname_norm}\n{head[:2000]}"
    for kind, pattern in _KIND_PATTERNS:
        if pattern.search(combined):
            return kind
    return "неизвестно"


