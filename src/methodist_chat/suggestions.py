"""Генерация контекстных подсказок по загруженному документу.

После загрузки файла модуль анализирует его тип (РПД, ФОС, лекция и т.д.)
и предлагает пользователю готовые действия в виде кликабельных кнопок.

Подсказки генерируются двумя путями:
1. **Статические (fallback)**: по типу документа — всегда доступны, не
   требуют LLM-вызова.
2. **LLM-генерируемые**: быстрый ``llm.quick()`` по первым ~1500 символам
   файла. Если LLM недоступен или ошибся — автоматический fallback на
   статические.

Кэш: подсказки привязаны к (filename, head_hash) — при повторном рендере
Streamlit не пересчитывает.
"""

