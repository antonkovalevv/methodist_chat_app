class QuickLLM(Protocol):
    """Достаточно метода ``quick`` — одноразовый system+user вызов."""

    def quick(
        self,
        *,
        system: str,
        user: str,
        temperature: float = ...,
        max_tokens: int = ...,
    ) -> str: ...


