_PROFILES: dict[str, str] = {
    "full": SYSTEM_PROMPT_TEMPLATE,
    "balanced": SYSTEM_PROMPT_BALANCED,
    "short": SYSTEM_PROMPT_SHORT,
}


def _resolve_profile(profile: str | None) -> str:
    """Безопасный резолвер профиля с дефолтом и логированием неизвестных."""
    name = (profile or os.getenv("PROMPT_PROFILE") or "full").strip().lower()
    if name not in _PROFILES:
        # Тихий фолбэк — не валим UI на опечатке в .env.
        name = "full"
    return name


def build_system_prompt(
    *,
    tools_block: str,
    document_card: str,
    profile: str | None = None,
) -> str:
    """Собирает системный промпт под выбранный профиль.

    profile: ``full`` | ``balanced`` | ``short`` (см. модульный docstring).
    Если ``None`` — берётся из ``PROMPT_PROFILE`` env-переменной;
    если её нет — ``full``.
    """
    today = date.today()
    name = _resolve_profile(profile)
    template = _PROFILES[name]
    return template.format(
        today=today.isoformat(),
        year_from_default=today.year - 5,
        tools_block=tools_block.strip() or "(инструменты не зарегистрированы)",
        document_card=document_card.strip() or "(файл не загружен)",
    )


# ---------------------------------------------------------------------------
# Карточка документа (рендерится в раздел 9 системного промпта)
# ---------------------------------------------------------------------------


def render_document_card(
    *,
    filename: str,
    char_count: int,
    head_preview: str,
    head_preview_max_chars: int = 1500,
) -> str:
    if not filename:
        return "Файл не загружен. Если методист задаёт вопрос про документ — попроси прикрепить файл."
    head = (head_preview or "").strip()
    if len(head) > head_preview_max_chars:
        head = head[:head_preview_max_chars] + "…[усечено]"
    # Лейбл должен соответствовать тому, сколько на самом деле уместилось
    # — иначе модель видит «первые 8000» при тексте на 2000 символов.
    actual_chars = min(head_preview_max_chars, len(head))
    return (
        f"Файл: {filename}\n"
        f"Размер: {char_count} символов\n"
        f"Начало документа (первые {actual_chars} символов):\n"
        f"---\n{head}\n---\n\n"
        "Чтобы прочитать другие части документа — вызывай read_attachment."
    )


